/** Sleutel van een foto-URL uit de bibliotheek (map + bestandsnaam). */
function keyOf(src: string): string {
  const i = src.indexOf("/bibliotheek/");
  return i === -1 ? "" : src.slice(i + "/bibliotheek/".length);
}

/** Uitsnede voor deze foto: [desktop, gsm]. Terugval: iets boven het midden. */
export function focusFor(src: string): [string, string] {
  return PHOTO_FOCUS[keyOf(src)] ?? ["50% 45%", "50% 50%"];
}

/** Waar of de foto te klein/donker/licht is om groot te tonen. */
export function isLowQuality(src: string): boolean {
  return LOW_QUALITY.has(keyOf(src));
}

/** Waar of de foto liggend en scherp genoeg is voor de brede sfeerband. */
export function isBandReady(src: string): boolean {
  return BAND_READY.has(keyOf(src));
}
